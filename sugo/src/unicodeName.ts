/**
 * 경로 세그먼트가 될 사용자 텍스트의 유니코드 정규화.
 *
 * **왜 필요한가(macOS 대응):** 한글 "로그인"은 완성형(NFC, `로그인`)과
 * 조합형(NFD, 초성+중성+종성 자모 나열) 두 표현이 있고 **화면에는 똑같이 보인다.**
 * macOS는 파일명을 조합형으로 다루는 경로가 있어(HFS+ readdir, Finder에서 복사한 이름,
 * mac에서 만든 zip 해제 결과 등) 사용자 입력이 NFD로 들어올 수 있다. 그런데 슬러그 화이트리스트
 * `[a-z0-9가-힣]`의 `가-힣`은 **완성형 음절만** 포함한다 — NFD 자모는 전부 탈락해서
 * "로그인 기능"과 "결제 연동"이 **둘 다 `untitled`로 붕괴하고 같은 디렉터리로 충돌한다.**
 * Windows에서는 재현되지 않아 조용히 mac에서만 PRD/work-result를 덮어쓴다.
 *
 * 그래서 슬러그를 만들기 전에 항상 NFC로 합성한다. 두 플랫폼에서 같은 이름 → 같은 경로.
 */
export function toNfc(text: string): string {
  return text.normalize("NFC");
}
